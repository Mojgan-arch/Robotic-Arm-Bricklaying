def test_wave_loader_interlocks_100_pieces_with_shifting_rotation(monkeypatch):
    import numpy as np
    from masonmind.orchestrator import Orchestrator
    def unexpected_generation(*args):
        raise AssertionError("Wave fixture must retain the reviewed wave parameters")
    monkeypatch.setattr(Orchestrator, "run_phase_a", unexpected_generation)
    state, preview, review, log, status = prepare_design("", "B3", 7, "mock", tested_wall="wave")
    design = state['design']
    assert len(state['sequence'].order) == 100
    assert state['sequence'].report.passed
    assert design.program.n_courses == 8
    assert design.program.bricks_per_course == 12
    assert design.program.bond == 'running'
    assert design.program.gap_ratio == .12
    assert sum(b.brick_type == 'half' for b in design.bricks) == 8
    from masonmind.design.sequencer import dependencies
    graph = dependencies(design, state['owner'].config)
    # A wall interlocks neighbouring stacks instead of forming isolated fins.
    assert sum(len(supports) >= 2 for supports in graph.values()) > 65
    reached = {next(iter(graph))}
    while True:
        expanded = reached | {name for name, supports in graph.items() if supports & reached}
        expanded |= set().union(*(graph[name] for name in reached))
        if expanded == reached:
            break
        reached = expanded
    assert reached == set(graph), 'The wall must form one connected support network'
    assert state['owner'].config['planning']['contact_velocity'] == .8
    assert state['owner'].config['planning']['contact_acceleration'] == 1.5
    assert state['owner'].config['scan']['extent_recentering'] is True
    base_yaw = state['owner'].config['geometry']['wall_yaw_deg']
    for brick in design.bricks:
        if brick.brick_type == 'half':
            continue
        expected = 20 * np.sin(2 * np.pi * (brick.index + .5) / 12 + .1 * brick.course)
        assert abs(brick.yaw_deg - base_yaw - expected) < 1e-8
    assert '100 bricks' in status
    assert 'not generated from the text box' in status


