def test_clarification_restores_generate_and_shows_answer_controls(monkeypatch):
    from masonmind import ui
    from masonmind.interaction import ClarificationRequired
    def needs_answer(*args):
        raise ClarificationRequired(["Use a straight wall instead of an arc?"])
    monkeypatch.setattr(ui, "prepare_design", needs_answer)
    app = ui.create_app()
    callback = next(f.fn for f in app.fns.values() if f.fn.__name__ == "prepare_callback")
    updates = list(callback("An arc", "B3", 7, "ollama", "local"))
    final = updates[-1]
    assert final[0] is None
    assert final[5]["interactive"] is False
    assert "straight wall" in final[7]["value"]
    assert final[8]["visible"] and final[9]["visible"]
    assert final[10]["interactive"] is True
    assert "RuntimeError" not in final[4]
    from masonmind.interaction import answered_brief
    received = []
    def approved(brief, *args):
        received.append(brief)
        return {"reviewed": True}, "preview.png", {}, "Agent review", "Verified"
    monkeypatch.setattr(ui, "prepare_design", approved)
    revised = answered_brief("An arc", "Use a straight wall")
    next_run = list(callback(revised, "B3", 7, "ollama", "local"))[-1]
    assert received == [revised]
    assert next_run[0] == {"reviewed": True}
    assert next_run[5]["interactive"] is True
    assert next_run[10]["interactive"] is True
